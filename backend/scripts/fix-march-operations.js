function esc(s) { return s.replace(/'/g, "''"); }

async function main() {
  const pool = await sql.connect(dbConfig);
  console.log('Подключено к БД\n');

  // 1. Build user lookup
  const usersRes = await pool.request().query(`SELECT id, employee_id, fio FROM users`);
  const eidToId = new Map();
  const fioToId = new Map();
  for (const u of usersRes.recordset) {
    const eid = u.employee_id.trim().replace(/^0+/, '');
    eidToId.set(eid, u.id);
    fioToId.set(u.fio.trim().toUpperCase(), { id: u.id, eid: u.employee_id.trim() });
  }

  // 2. Resolve SAP names to employee_ids
  for (const [sapName, eid] of Object.entries(SAP_NAME_MAP)) {
    if (eid) continue; // already known
    const pattern = FIO_PATTERNS[sapName];
    if (!pattern) continue;
    const res = await pool.request()
      .input('p', sql.NVarChar(200), '%' + pattern + '%')
      .query(`SELECT id, employee_id FROM users WHERE fio LIKE @p`);
    if (res.recordset.length > 0) {
      const found = res.recordset[0];
      SAP_NAME_MAP[sapName] = found.employee_id.trim().replace(/^0+/, '');
      console.log(`  Resolved: ${sapName} -> ${found.employee_id}`);
    }
  }

  // 3. Get warehouse_code for user (default 02DQ)
  const whRes = await pool.request().query(`
    SELECT u.id, w.code FROM users u LEFT JOIN warehouses w ON u.warehouse_id = w.id
  `);
  const userWh = new Map();
  for (const r of whRes.recordset) {
    userWh.set(r.id, r.code || '02DQ');
  }

  // 4. Resolve all ops to user_ids
  const resolvedOps = [];
  const unresolved = new Set();

  for (const [wcr, resource, count, opType, rate, amount] of OPS) {
    if (amount === 0 || count === 0) continue;

    let eid;
    if (/^\d+$/.test(resource)) {
      eid = resource;
    } else {
      eid = SAP_NAME_MAP[resource];
    }

    if (!eid) {
      unresolved.add(resource);
      continue;
    }

    const userId = eidToId.get(eid);
    if (!userId) {
      unresolved.add(`${resource} (eid=${eid})`);
      continue;
    }

    const whCode = userWh.get(userId) || '02DQ';
    resolvedOps.push({ userId, whCode, wcr, opType, count, amount });
  }

  if (unresolved.size > 0) {
    console.log(`\nНе найдены: ${[...unresolved].join(', ')}`);
  }
  console.log(`\nРазрешено операций: ${resolvedOps.length}`);

  // 5. Get unique user_ids
  const affectedUsers = new Set(resolvedOps.map(o => o.userId));
  console.log(`Затронуто сотрудников: ${affectedUsers.size}`);

  // 6. Delete March operations for affected users
  for (const uid of affectedUsers) {
    await pool.request().input('uid', sql.Int, uid).query(`
      DELETE FROM operations
      WHERE user_id = @uid
        AND operation_date >= '2026-03-01'
        AND operation_date < '2026-04-01'
    `);
  }
  console.log('Удалены старые мартовские операции\n');

  // 7. Insert new operations (batch by 50)
  const BATCH = 50;
  let inserted = 0;

  for (let i = 0; i < resolvedOps.length; i += BATCH) {
    const chunk = resolvedOps.slice(i, i + BATCH);
    const values = chunk.map(o => {
      return `(${o.userId}, N'${esc(o.whCode)}', N'${esc(o.opType)}', NULL, ${o.count}, 0, '2026-03-15', ${o.amount}, NULL, N'${esc(o.wcr)}', NULL)`;
    }).join(',\n');

    await pool.request().query(`
      INSERT INTO operations (user_id, warehouse_code, operation_type, participant_area, count, actdura, operation_date, amount, sap_order_id, wcr_code, aarea)
      VALUES ${values}
    `);
    inserted += chunk.length;
  }
  console.log(`Вставлено: ${inserted} операций\n`);

  // 8. Verify totals
  console.log('=== ПРОВЕРКА СУММ ===\n');
  const check = await pool.request().query(`
    SELECT u.fio, u.employee_id, ROUND(SUM(o.amount), 2) as total, COUNT(*) as ops
    FROM operations o
    INNER JOIN users u ON o.user_id = u.id
    WHERE o.operation_date >= '2026-03-01' AND o.operation_date < '2026-04-01'
      AND u.id IN (${[...affectedUsers].join(',')})
    GROUP BY u.fio, u.employee_id
    ORDER BY total DESC
  `);
  for (const r of check.recordset) {
    console.log(`${r.fio.padEnd(50)} ${parseFloat(r.total).toFixed(0).padStart(10)} (${r.ops} ops)`);
  }

  await pool.close();
  console.log('\nГОТОВО');
}

main().catch(e => { console.error('FATAL:', e.message, e.stack); process.exit(1); });
