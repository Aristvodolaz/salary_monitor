async function run() {
  const pool = await sql.connect(cfg);

  const rows = await pool.request().query(`
    SELECT u.fio, ss.total_amount
    FROM salary_summary ss JOIN users u ON u.id = ss.user_id
    WHERE ss.period_start = '2026-02-01' ORDER BY u.fio
  `);

  // Build lookup by fio
  const ssMap = new Map();
  for (const row of rows.recordset) {
    ssMap.set(row.fio.toUpperCase().trim(), row.total_amount);
  }

  console.log('╔══════════════════════════════════════════════════════════════╗');
  console.log('║  СРАВНЕНИЕ С ЭТАЛОНОМ — ФЕВРАЛЬ 2026                        ║');
  console.log('╚══════════════════════════════════════════════════════════════╝\n');
  console.log('  ' + 'Сотрудник'.padEnd(38) + 'Наша'.padStart(10) + 'Эталон'.padStart(10) + '  Δ');
  console.log('  ' + '─'.repeat(65));

  let ok = 0, diff = 0, notFound = 0;
  const TOLERANCE = 3; // руб

  for (const [key, refVal] of Object.entries(REF)) {
    const searches = KEY_MAP[key] || [key];
    let found = null;
    for (const search of searches) {
      for (const [fio, amt] of ssMap.entries()) {
        if (fio.includes(search.toUpperCase())) {
          found = { fio, amt };
          break;
        }
      }
      if (found) break;
    }

    if (!found) {
      console.log(`  ⚠️  НЕ НАЙДЕН: ${key}`);
      notFound++;
      continue;
    }

    const d = found.amt - refVal;
    const absD = Math.abs(d);
    if (absD <= TOLERANCE) {
      ok++;
    } else {
      const sign = d > 0 ? '+' : '';
      console.log(`  ❌ ${found.fio.substring(0,38).padEnd(38)} ${found.amt.toFixed(0).padStart(9)} ${refVal.toString().padStart(9)}  ${sign}${d.toFixed(0)}`);
      diff++;
    }
  }

  console.log('\n' + '─'.repeat(67));
  console.log(`  ✅ Совпадают (±${TOLERANCE} руб): ${ok}`);
  console.log(`  ❌ Расхождения: ${diff}`);
  console.log(`  ⚠️  Не найдено: ${notFound}`);

  const totalRes = await pool.request().query(`SELECT SUM(total_amount) as t FROM salary_summary WHERE period_start = '2026-02-01'`);
  console.log(`\n  Общий фонд: ${totalRes.recordset[0].t.toFixed(2)}`);

  await pool.close();
}
run().catch(console.error);
